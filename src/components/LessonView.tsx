import { useState } from "react";
import { toast } from "sonner";
import { ArrowLeft, ArrowRight, Bookmark, BookmarkCheck, Check, Copy, Download, RotateCcw, X } from "lucide-react";
import { lessonToMarkdown, scoreQuiz, type Lesson } from "@/lib/lesson";
import { useApp } from "@/lib/store";
import { CodeBlock, RichText } from "./RichText";

const TABS = ["Read", "Practice", "Flashcards"] as const;

export function SourceBadge({ lesson }: { lesson: Lesson }) {
  return (
    <span className="inline-flex items-center rounded-full border border-border bg-muted px-2.5 py-0.5 text-[11px] font-medium text-muted-foreground">
      {lesson.source === "sample" ? "Built-in sample (not live AI)" : "Generated by Gemini"}
    </span>
  );
}

export function LessonView({ lesson, onClose }: { lesson: Lesson; onClose?: () => void }) {
  const [tab, setTab] = useState<(typeof TABS)[number]>("Read");
  const { saveLesson, isSaved } = useApp();
  const saved = isSaved(lesson.id);
  const md = lessonToMarkdown(lesson);

  return (
    <article className="card-soft p-5 sm:p-8" aria-labelledby="lesson-title">
      <div className="flex flex-wrap items-start justify-between gap-4">
        <div className="min-w-0 max-w-2xl">
          <div className="mb-3 flex flex-wrap items-center gap-2">
            <SourceBadge lesson={lesson} />
            <span className="text-xs text-muted-foreground">
              {lesson.format} · {lesson.level} · {lesson.language}
            </span>
          </div>
          <h2 id="lesson-title" className="text-3xl font-medium text-foreground sm:text-4xl">{lesson.title}</h2>
          <p className="mt-3 text-muted-foreground">{lesson.summary}</p>
        </div>
        <div className="flex flex-wrap gap-2">
          <ActionBtn
            onClick={async () => {
              try {
                await navigator.clipboard.writeText(md);
                toast.success("Copied as Markdown");
              } catch {
                toast.error("Couldn't access the clipboard");
              }
            }}
            icon={<Copy className="h-4 w-4" />}
            label="Copy"
          />
          <ActionBtn
            onClick={() => {
              const url = URL.createObjectURL(new Blob([md], { type: "text/markdown" }));
              const a = document.createElement("a");
              a.href = url;
              a.download = `${lesson.title.replace(/[^\p{L}\p{N}]+/gu, "-").slice(0, 60) || "lesson"}.md`;
              a.click();
              URL.revokeObjectURL(url);
            }}
            icon={<Download className="h-4 w-4" />}
            label="Markdown"
          />
          <ActionBtn
            primary={!saved}
            onClick={() => {
              saveLesson(lesson);
              toast.success("Saved to My library (this browser)");
            }}
            icon={saved ? <BookmarkCheck className="h-4 w-4" /> : <Bookmark className="h-4 w-4" />}
            label={saved ? "Saved" : "Save lesson"}
          />
          {onClose ? <ActionBtn onClick={onClose} icon={<X className="h-4 w-4" />} label="Close" /> : null}
        </div>
      </div>

      <div role="tablist" aria-label="Lesson views" className="mt-7 inline-flex rounded-lg border border-border bg-muted p-1">
        {TABS.map((t) => (
          <button
            key={t}
            role="tab"
            aria-selected={tab === t}
            onClick={() => setTab(t)}
            className={`rounded-md px-4 py-1.5 text-sm transition focus-visible:outline-2 focus-visible:outline-ring ${
              tab === t ? "bg-card font-medium text-foreground shadow-sm" : "text-muted-foreground hover:text-foreground"
            }`}
          >
            {t}
            {t === "Practice" ? ` (${lesson.quiz.length})` : t === "Flashcards" ? ` (${lesson.flashcards.length})` : ""}
          </button>
        ))}
      </div>

      <div className="mt-6" role="tabpanel">
        {tab === "Read" && <ReadTab lesson={lesson} />}
        {tab === "Practice" && <Quiz key={lesson.id} lesson={lesson} />}
        {tab === "Flashcards" && <Flashcards key={lesson.id} lesson={lesson} />}
      </div>
    </article>
  );
}

function ActionBtn({ onClick, icon, label, primary }: { onClick: () => void; icon: React.ReactNode; label: string; primary?: boolean }) {
  return (
    <button
      onClick={onClick}
      className={`inline-flex items-center gap-1.5 rounded-lg border px-3 py-1.5 text-sm transition focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-ring ${
        primary ? "border-primary bg-primary text-primary-foreground hover:bg-primary/90" : "border-border bg-card text-foreground hover:bg-muted"
      }`}
    >
      {icon} {label}
    </button>
  );
}

function ReadTab({ lesson }: { lesson: Lesson }) {
  return (
    <div className="grid gap-8 lg:grid-cols-[1fr_260px]">
      <div className="space-y-8">
        {lesson.sections.map((s, i) => (
          <section key={i} className="space-y-3">
            <h3 className="text-xl font-medium text-foreground">{s.heading}</h3>
            <RichText text={s.body} />
            {s.code ? <CodeBlock code={s.code} lang={s.codeLanguage} /> : null}
          </section>
        ))}
      </div>
      <aside className="h-fit rounded-xl bg-sage-soft/60 p-5">
        <h3 className="text-base font-medium text-foreground">Key takeaways</h3>
        <ul className="mt-3 space-y-2.5 text-sm text-foreground/85">
          {lesson.keyTakeaways.map((t, i) => (
            <li key={i} className="flex gap-2">
              <Check className="mt-0.5 h-4 w-4 shrink-0 text-primary" aria-hidden /> <span>{t}</span>
            </li>
          ))}
        </ul>
      </aside>
    </div>
  );
}

export function Quiz({ lesson }: { lesson: Lesson }) {
  const [answers, setAnswers] = useState<(number | null)[]>(() => lesson.quiz.map(() => null));
  const [submitted, setSubmitted] = useState(false);
  const score = scoreQuiz(lesson.quiz, answers);
  const remaining = answers.filter((a) => a === null).length;

  return (
    <div className="space-y-5">
      {lesson.quiz.map((q, qi) => (
        <fieldset key={qi} className="rounded-xl border border-border p-5">
          <legend className="px-1 text-sm font-medium text-muted-foreground">Question {qi + 1}</legend>
          <p className="mb-4 font-medium text-foreground">{q.question}</p>
          <div className="grid gap-2 sm:grid-cols-2">
            {q.options.map((o, oi) => {
              const chosen = answers[qi] === oi;
              const correct = q.correctIndex === oi;
              let cls = chosen ? "border-primary bg-accent" : "border-border hover:bg-muted";
              if (submitted && correct) cls = "border-success bg-sage-soft";
              else if (submitted && chosen) cls = "border-destructive bg-destructive/5";
              return (
                <label key={oi} className={`flex cursor-pointer items-start gap-3 rounded-lg border px-3 py-2.5 text-sm transition focus-within:outline-2 focus-within:outline-ring ${cls}`}>
                  <input
                    type="radio"
                    name={`q-${lesson.id}-${qi}`}
                    className="mt-0.5 accent-primary"
                    checked={chosen}
                    disabled={submitted}
                    onChange={() => setAnswers((a) => a.map((v, i) => (i === qi ? oi : v)))}
                  />
                  <span>
                    <span className="mr-1 font-medium text-muted-foreground">{String.fromCharCode(65 + oi)}.</span>
                    {o}
                  </span>
                </label>
              );
            })}
          </div>
          {submitted ? (
            <p className={`mt-4 rounded-lg p-3 text-sm ${answers[qi] === q.correctIndex ? "bg-sage-soft text-foreground" : "bg-muted text-foreground"}`}>
              <strong>{answers[qi] === q.correctIndex ? "Correct. " : `Answer: ${String.fromCharCode(65 + q.correctIndex)}. `}</strong>
              {q.explanation}
            </p>
          ) : null}
        </fieldset>
      ))}
      <div className="flex flex-wrap items-center gap-4">
        {!submitted ? (
          <>
            <button
              disabled={score === null}
              onClick={() => setSubmitted(true)}
              className="rounded-lg bg-primary px-5 py-2.5 text-sm font-medium text-primary-foreground transition hover:bg-primary/90 disabled:cursor-not-allowed disabled:opacity-50"
            >
              Check answers
            </button>
            {remaining > 0 ? <span className="text-sm text-muted-foreground">Answer {remaining} more to see your score.</span> : null}
          </>
        ) : (
          <>
            <p className="font-serif text-2xl text-foreground" role="status">
              You scored {score} / {lesson.quiz.length}
            </p>
            <button
              onClick={() => {
                setAnswers(lesson.quiz.map(() => null));
                setSubmitted(false);
              }}
              className="inline-flex items-center gap-1.5 rounded-lg border border-border px-4 py-2 text-sm hover:bg-muted"
            >
              <RotateCcw className="h-4 w-4" /> Retry
            </button>
          </>
        )}
      </div>
    </div>
  );
}

export function Flashcards({ lesson }: { lesson: Lesson }) {
  const [i, setI] = useState(0);
  const [flipped, setFlipped] = useState(false);
  const card = lesson.flashcards[i]!;
  const go = (d: number) => {
    setFlipped(false);
    setI((x) => (x + d + lesson.flashcards.length) % lesson.flashcards.length);
  };
  return (
    <div className="mx-auto max-w-xl">
      <button
        className="flip-card block h-64 w-full text-left focus-visible:outline-2 focus-visible:outline-offset-4 focus-visible:outline-ring rounded-xl"
        data-flipped={flipped}
        onClick={() => setFlipped((f) => !f)}
        aria-label={flipped ? `Answer: ${card.back}. Click to show question.` : `Question: ${card.front}. Click to reveal answer.`}
      >
        <div className="flip-inner relative h-full w-full">
          <div className="flip-face absolute inset-0 flex flex-col justify-between rounded-xl border border-border bg-card p-6">
            <span className="text-xs uppercase tracking-wider text-muted-foreground">Prompt</span>
            <p className="text-center font-serif text-2xl text-foreground">{card.front}</p>
            <span className="text-center text-xs text-muted-foreground">Tap to flip</span>
          </div>
          <div className="flip-face flip-back absolute inset-0 flex flex-col justify-between rounded-xl border border-primary/30 bg-sage-soft p-6">
            <span className="text-xs uppercase tracking-wider text-muted-foreground">Answer</span>
            <p className="text-center text-lg text-foreground">{card.back}</p>
            <span className="text-center text-xs text-muted-foreground">Tap to flip back</span>
          </div>
        </div>
      </button>
      <div className="mt-5 flex items-center justify-between">
        <button onClick={() => go(-1)} className="inline-flex items-center gap-1.5 rounded-lg border border-border px-4 py-2 text-sm hover:bg-muted">
          <ArrowLeft className="h-4 w-4" /> Previous
        </button>
        <span className="text-sm text-muted-foreground" aria-live="polite">
          {i + 1} / {lesson.flashcards.length}
        </span>
        <button onClick={() => go(1)} className="inline-flex items-center gap-1.5 rounded-lg border border-border px-4 py-2 text-sm hover:bg-muted">
          Next <ArrowRight className="h-4 w-4" />
        </button>
      </div>
    </div>
  );
}
