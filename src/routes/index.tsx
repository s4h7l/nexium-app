import { createFileRoute, Link } from "@tanstack/react-router";
import { useEffect, useRef, useState } from "react";
import { ArrowRight, Loader2, MessageCircle, Square, TriangleAlert } from "lucide-react";
import { AppShell, useGeminiStatus } from "@/components/AppShell";
import { BookArt } from "@/components/BookArt";
import { LessonView } from "@/components/LessonView";
import { OptionGroup } from "@/components/OptionGroup";
import { postJson, ClientError } from "@/lib/api-client";
import { FORMATS, LANGUAGES, LENGTHS, LEVELS, PROMPT_MAX, type Format, type Lesson, type LessonContent } from "@/lib/lesson";
import { SAMPLES } from "@/lib/samples";
import { useApp } from "@/lib/store";

export const Route = createFileRoute("/")({
  head: () => ({
    meta: [
      { title: "Learning studio — AI Education Assistant" },
      { name: "description", content: "Turn any topic into lessons, revision notes, flashcards, quizzes or study plans generated by Google Gemini." },
      { property: "og:title", content: "Learning studio — AI Education Assistant" },
      { property: "og:description", content: "Turn any topic into something that clicks. Learn your way, at your pace." },
      { property: "og:type", content: "website" },
      { name: "twitter:card", content: "summary_large_image" },
    ],
  }),
  component: Studio,
});

function Studio() {
  const { prefs, setPrefs, current, setCurrent, sessionKey, markVerified } = useApp();
  const status = useGeminiStatus();
  const [prompt, setPrompt] = useState("");
  const [format, setFormat] = useState<Format>("Lesson");
  const [loading, setLoading] = useState(false);
  const [elapsed, setElapsed] = useState(0);
  const [error, setError] = useState<string | null>(null);
  const abortRef = useRef<AbortController | null>(null);
  const resultRef = useRef<HTMLDivElement>(null);
  const promptRef = useRef<HTMLTextAreaElement>(null);

  useEffect(() => {
    setPrompt("");
    setError(null);
    abortRef.current?.abort();
    promptRef.current?.focus();
  }, [sessionKey]);

  useEffect(() => {
    if (!loading) return;
    const t = setInterval(() => setElapsed((e) => e + 1), 1000);
    return () => clearInterval(t);
  }, [loading]);

  const notConnected = status.data && !status.data.configured;

  async function generate(e: React.FormEvent) {
    e.preventDefault();
    if (prompt.trim().length < 3) {
      setError("Please describe what you'd like to learn (at least a few words).");
      return;
    }
    setError(null);
    setLoading(true);
    setElapsed(0);
    const ac = new AbortController();
    abortRef.current = ac;
    try {
      const { lesson } = await postJson<{ lesson: LessonContent }>(
        "/api/generate",
        { prompt, format, ...prefs },
        ac.signal,
      );
      const full: Lesson = {
        ...lesson,
        id: crypto.randomUUID(),
        format,
        ...prefs,
        prompt,
        source: "gemini",
        createdAt: new Date().toISOString(),
      };
      markVerified();
      setCurrent(full);
      setTimeout(() => resultRef.current?.scrollIntoView({ behavior: "smooth", block: "start" }), 50);
    } catch (err) {
      if (err instanceof ClientError && err.code === "cancelled") setError("Generation cancelled.");
      else setError(err instanceof Error ? err.message : "Something went wrong.");
    } finally {
      setLoading(false);
      abortRef.current = null;
    }
  }

  return (
    <AppShell crumb="Learning studio">
      {/* Hero */}
      <section className="grid items-center gap-8 pb-10 md:grid-cols-[1.25fr_1fr]">
        <div>
          <p className="mb-4 text-xs font-medium uppercase tracking-[0.18em] text-sage">Learning studio</p>
          <h1 className="text-4xl font-normal leading-[1.08] text-foreground sm:text-5xl lg:text-[3.6rem]">
            A little curiosity.
            <br />A whole lot of <em className="font-normal italic text-sage">possibility.</em>
          </h1>
          <p className="mt-5 max-w-md text-lg text-muted-foreground">Turn any topic into something that clicks. Learn your way, at your pace.</p>
        </div>
        <BookArt />
      </section>

      <div className="grid gap-6 lg:grid-cols-[1fr_300px]">
        {/* Studio form */}
        <form onSubmit={generate} className="card-soft p-5 sm:p-7" aria-busy={loading}>
          <label htmlFor="prompt" className="font-serif text-xl text-foreground">What would you like to learn?</label>
          <textarea
            id="prompt"
            ref={promptRef}
            value={prompt}
            maxLength={PROMPT_MAX}
            onChange={(e) => setPrompt(e.target.value)}
            placeholder="e.g. Explain recursion with a simple Python example, then test me on it."
            rows={5}
            className="mt-3 w-full resize-y rounded-lg border border-input bg-background p-4 text-[15px] text-foreground placeholder:text-muted-foreground/70 focus:border-ring focus:outline-none focus:ring-2 focus:ring-ring/30"
          />
          <div className="mt-1 text-right text-xs text-muted-foreground">
            {prompt.length} / {PROMPT_MAX}
          </div>
          <div className="mt-4 grid gap-5">
            <OptionGroup label="Format" options={FORMATS} value={format} onChange={setFormat} />
            <div className="grid gap-5 md:grid-cols-3">
              <OptionGroup label="Level" options={LEVELS} value={prefs.level} onChange={(level) => setPrefs({ level })} />
              <OptionGroup label="Length" options={LENGTHS} value={prefs.length} onChange={(length) => setPrefs({ length })} />
              <OptionGroup label="Language" options={LANGUAGES} value={prefs.language} onChange={(language) => setPrefs({ language })} />
            </div>
          </div>

          {notConnected ? (
            <div role="alert" className="mt-5 flex gap-3 rounded-lg border border-destructive/30 bg-destructive/5 p-4 text-sm text-foreground">
              <TriangleAlert className="h-4 w-4 shrink-0 text-destructive" />
              Gemini isn't connected on the server, so generation is unavailable. You can still explore the built-in samples below.
            </div>
          ) : null}
          {error ? (
            <div role="alert" className="mt-5 flex gap-3 rounded-lg border border-destructive/30 bg-destructive/5 p-4 text-sm text-foreground">
              <TriangleAlert className="h-4 w-4 shrink-0 text-destructive" /> {error}
            </div>
          ) : null}

          <div className="mt-6 flex flex-wrap items-center gap-3">
            <button
              type="submit"
              disabled={loading || !!notConnected}
              className="inline-flex items-center gap-2 rounded-lg bg-primary px-5 py-2.5 text-sm font-medium text-primary-foreground transition hover:bg-primary/90 disabled:opacity-60 focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-ring"
            >
              {loading ? <Loader2 className="h-4 w-4 animate-spin" /> : <ArrowRight className="h-4 w-4" />}
              {loading ? "Gemini is writing…" : "Generate content"}
            </button>
            {loading ? (
              <>
                <button
                  type="button"
                  onClick={() => abortRef.current?.abort()}
                  className="inline-flex items-center gap-2 rounded-lg border border-border px-4 py-2.5 text-sm hover:bg-muted"
                >
                  <Square className="h-3.5 w-3.5" /> Cancel
                </button>
                <span className="text-sm text-muted-foreground" aria-live="polite">
                  {elapsed}s{elapsed > 25 ? " — longer formats can take up to a minute" : ""}
                </span>
              </>
            ) : null}
          </div>
        </form>

        {/* Right column */}
        <div className="flex flex-col gap-6">
          <div className="card-soft bg-sage-soft/50 p-6">
            <h2 className="text-2xl font-normal leading-tight text-foreground">
              Less memorizing.
              <br />
              <em className="italic text-sage">More understanding.</em>
            </h2>
            <p className="mt-3 text-sm text-muted-foreground">
              Every result comes with a reading view, a practice quiz with explanations, and flashcards to lock it in.
            </p>
          </div>
          <div className="card-soft p-6">
            <MessageCircle className="h-5 w-5 text-primary" aria-hidden />
            <h2 className="mt-3 text-lg font-medium text-foreground">Stuck on something?</h2>
            <p className="mt-1 text-sm text-muted-foreground">Ask your Gemini tutor follow-up questions in {prefs.language}, at {prefs.level.toLowerCase()} level.</p>
            <Link
              to="/tutor"
              className="mt-4 inline-flex items-center gap-1.5 text-sm font-medium text-primary hover:underline"
            >
              Ask your tutor <ArrowRight className="h-4 w-4" />
            </Link>
          </div>
        </div>
      </div>

      <div ref={resultRef} className="scroll-mt-20">
        {current ? (
          <div className="mt-8">
            <LessonView lesson={current} onClose={() => setCurrent(null)} />
          </div>
        ) : null}
      </div>

      {/* Samples */}
      <section className="mt-14" aria-labelledby="samples-heading">
        <div className="mb-5 flex flex-wrap items-end justify-between gap-2">
          <div>
            <h2 id="samples-heading" className="text-2xl font-normal text-foreground">Built-in samples</h2>
            <p className="text-sm text-muted-foreground">Prepared examples — not live AI. Explore them anytime, even without a Gemini connection.</p>
          </div>
        </div>
        <div className="grid gap-4 md:grid-cols-3">
          {SAMPLES.map((s) => (
            <button
              key={s.id}
              onClick={() => {
                setCurrent(s);
                setTimeout(() => resultRef.current?.scrollIntoView({ behavior: "smooth", block: "start" }), 50);
              }}
              className="card-soft group flex flex-col p-5 text-left transition hover:border-primary/40 focus-visible:outline-2 focus-visible:outline-ring"
            >
              <div className="flex flex-wrap gap-1.5 text-[11px] text-muted-foreground">
                <span className="rounded-full border border-border bg-muted px-2 py-0.5">Built-in sample (not live AI)</span>
                <span className="rounded-full border border-border px-2 py-0.5">Beginner</span>
                <span className="rounded-full border border-border px-2 py-0.5">English</span>
              </div>
              <h3 className="mt-3 text-lg font-medium text-foreground">{s.title}</h3>
              <p className="mt-1 line-clamp-3 text-sm text-muted-foreground">{s.summary}</p>
              <span className="mt-4 inline-flex items-center gap-1 text-sm font-medium text-primary">
                Open sample <ArrowRight className="h-4 w-4 transition group-hover:translate-x-0.5" />
              </span>
            </button>
          ))}
        </div>
      </section>
    </AppShell>
  );
}
